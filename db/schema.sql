-- Defence in depth: RLS with no policies denies any non-owner role (e.g. a Data API role);
-- the owner connection used by the server bypasses RLS. The anon/authenticated revokes only run
-- where those roles exist (some hosted-Postgres setups); on Neon / plain Postgres they are skipped.
ALTER TABLE submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE utm_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE utm_campaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE utm_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE utm_clicks ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_attempts ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE role_name TEXT;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON submissions, utm_channels, utm_campaigns, utm_links, utm_clicks, login_attempts FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', role_name);
        END IF;
    END LOOP;
END $$;

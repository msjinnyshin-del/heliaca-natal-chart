-- Natal chart admin store for Postgres (Neon or any Postgres 13+). Idempotent: safe to run again.
-- Run once (Neon SQL Editor or `psql "$DATABASE_URL_UNPOOLED" -f db/schema.sql`) before the first deploy;
-- the app never migrates Postgres at request time.
-- Mirrors SQLite migrations 1-3 in natal/store.py (SCHEMA_VERSION = 3).
-- The server connects as the database owner via DATABASE_URL; the public Data API roles get no access.

CREATE TABLE IF NOT EXISTS submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL,
    visitor_id TEXT,
    display_name TEXT,
    raw_input TEXT NOT NULL,
    status TEXT NOT NULL,
    error_code TEXT,
    summary TEXT,
    place TEXT,
    sun_sign TEXT,
    moon_sign TEXT,
    asc_sign TEXT,
    fingerprint TEXT,
    consent INTEGER NOT NULL DEFAULT 0 CHECK (consent IN (0, 1)),
    utm_source TEXT, utm_medium TEXT, utm_campaign TEXT, utm_content TEXT, utm_term TEXT,
    short_code TEXT
);
CREATE INDEX IF NOT EXISTS submissions_created_at ON submissions(created_at);
CREATE INDEX IF NOT EXISTS submissions_visitor ON submissions(visitor_id, created_at);
CREATE INDEX IF NOT EXISTS submissions_status ON submissions(status);
CREATE INDEX IF NOT EXISTS submissions_short_code ON submissions(short_code);

CREATE TABLE IF NOT EXISTS utm_channels (
    key TEXT PRIMARY KEY CHECK (length(key) BETWEEN 1 AND 64),
    label_ko TEXT NOT NULL,
    utm_source TEXT NOT NULL,
    utm_medium TEXT NOT NULL,
    note TEXT,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 100,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS utm_campaigns (
    key TEXT PRIMARY KEY CHECK (length(key) BETWEEN 1 AND 64),
    label_ko TEXT NOT NULL,
    note TEXT,
    starts_on TEXT,
    ends_on TEXT,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS utm_links (
    code TEXT PRIMARY KEY CHECK (length(code) = 6),
    target_path TEXT NOT NULL CHECK (
        substr(target_path, 1, 1) = '/' AND substr(target_path, 1, 2) <> '//'
        AND strpos(target_path, E'\\') = 0 AND strpos(target_path, ':') = 0 AND length(target_path) <= 200),
    channel_key TEXT REFERENCES utm_channels(key),
    campaign_key TEXT REFERENCES utm_campaigns(key),
    utm_source TEXT NOT NULL,
    utm_medium TEXT NOT NULL,
    utm_campaign TEXT NOT NULL,
    utm_content TEXT,
    memo TEXT,
    created_by TEXT,
    archived_at TEXT,
    created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS utm_links_active_combo
    ON utm_links(target_path, utm_source, utm_medium, utm_campaign, COALESCE(utm_content, ''))
    WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS utm_clicks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    clicked_at TEXT NOT NULL,
    counted INTEGER NOT NULL CHECK (counted IN (0, 1)),
    exclude_note TEXT CHECK (exclude_note IN ('head', 'preview-bot')),
    ua_family TEXT
);
CREATE INDEX IF NOT EXISTS utm_clicks_code ON utm_clicks(code, clicked_at);
CREATE INDEX IF NOT EXISTS utm_clicks_at ON utm_clicks(clicked_at);

CREATE TABLE IF NOT EXISTS login_attempts (
    key_hash TEXT NOT NULL,
    attempted_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS login_attempts_key ON login_attempts(key_hash, attempted_at);

CREATE TABLE IF NOT EXISTS shares (
    token TEXT PRIMARY KEY,
    kind TEXT NOT NULL,
    title TEXT,
    payload TEXT NOT NULL,
    delete_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);

